# ============ 机械臂动作参数 ============
# 注意：以下高度均以 panda_link7/link8（腕部法兰，pybullet IK 实际控制的连杆）为参考。
# 手（panda_hand）在 link8 下方 0.1034m，夹爪指尖再往下约 0.09m。
#
# ★ home（停靠）位姿，实测挑选出来的：EE 约在 (0.45, +0.30, 0.72)。
#   为什么必须是这个位置：相机在 y=-0.45 俯视，机械臂是白色的，
#   如果停在桌子近端就会挡住蓝方块/紫色区域的视线（实测蓝方块直接识别不到，
#   紫色区域中心被压掉 21mm）。停到桌子远端 = 手臂在所有目标"身后"，不遮挡。
#   实测该位姿下 5 个目标全部命中，平均误差 3.5mm、最大 5.4mm。
HOME_JOINTS = [0.4326, 0.2542, 0.1613, -2.2183, -0.0648, 2.4683, 0.6395]
HOVER_Z = TABLE_TOP + 0.20              # 移动时的悬停高度
# 抓取高度（以 link7/link8 URDF 帧为参考）。
# ★ 实测标定（dbg_graspz.py / dbg_finger.py）：
#   手掌底 = link7 - 0.177，指尖最低 = link7 - 0.223，方块顶 = 0.494。
#   手掌首次碰到方块顶时 link7 = 0.664，再往下就会把方块顶飞。
#   取 0.672 → 手掌底 0.495（离方块顶 1mm 余量），指尖 0.449（正好抱住整块）。
#   同时 0.672 - 0.20 = 0.472 = 方块静置于桌面时的中心高度，抓取/放置可复用同一高度。
GRASP_Z = TABLE_TOP + 0.222              # = 0.672
# 放置高度：方块被夹住时中心比 link7 低 0.2014m，区域板顶面 0.452。
# 若仍在 GRASP_Z 释放，方块底面 0.4499 会插进板里 2mm 被顶一下；
# 抬高 4mm → 底面 0.4539，离板 2mm 自然放下，回弹最小（实测落点漂移 <3mm）。
PLACE_Z = GRASP_Z + 0.004                # = 0.676
FINGER_OPEN = 0.04                      # 手指张开（米），张开后内间距约 82mm > 方块 44mm
# 闭合目标给 0.015（小于方块半宽 0.022），手指会真的压在方块两侧停住，
# 而不是一直往里挤 —— 视觉上是标准的两指夹持，不是穿模。
FINGER_CLOSE = 0.015
MAX_MOVE_STEPS = 900                    # 单次移动最多模拟步数
# 收敛判定（米）。配合 arm.move_to 的闭环补偿：
# 实测 tol=0.008→残差7.5mm，0.002→2mm，0.001→1mm 以内，取 1.5mm 兼顾精度与速度。
MOVE_TOL = 0.0015
# IK 求解器参数。★ residualThreshold 必须极小，否则 pybullet 提前判定收敛。
IK_ITERATIONS = 2000
IK_RESIDUAL = 1e-9
IK_FORCE = 120.0                        # 关节位置控制最大力矩
# 关节最大角速度（rad/s）。★ 不限制的话位控会在几帧内"甩"到位，
# 末端横扫桌面把方块撞飞（实测蓝方块被扫出桌沿）。限速后动作也更像真实机械臂。
MAX_JOINT_VEL = 1.2
# 安全转运高度：先竖直抬到这里再平移，保证指尖始终高于方块顶。
# 指尖在 link7 下方 0.223，SAFE_Z=0.85 → 指尖 0.627，比方块顶 0.494 高 133mm。
